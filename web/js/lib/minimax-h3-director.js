// #1679 / #1935 — MiniMaxH3Director's prompt, builder_state, and timeline_data widgets
// are derived write-backs of the node's in-memory builderState. A raw panel_set_widget
// write therefore appears to succeed (panel_query_graph reflects it) while the dependent
// widgets stay stale, and the next Director emit() regenerates all three from the stale
// closure. Refuse them before the generic write path can mutate the graph or await any
// object-info/network work.
//
// FACTS FROM THE PACK'S OWN SOURCE (darksidewalker/ComfyUI-DaSiWa-Nodes
// `js/minimax_h3_director.js` `install()` / `emit()` / `restorePersistedState()`), not
// inferred from the report:
//
//   1. `state` and `builderState` are CLOSURE LOCALS inside `install(node)`. timeline_data
//      is parsed ONCE at install (`let state = parseState(dataWidget.value)`). There is no
//      `_applyLoadedTimeline` equivalent.
//
//   2. `emit()` is the only write-back. It assigns prompt from `builderPromptForWidget`,
//      nests builderState onto timeline_data, and writes the builder_state widget:
//
//          promptWidget.value = resolved;
//          state.builder_state = builderState;
//          dataWidget.value = JSON.stringify(state);
//          builderWidget.value = JSON.stringify(builderState);
//
//   3. Python `build_guide()` prefers the builder_state WIDGET over
//      timeline_data.builder_state when the widget is non-empty:
//
//          builder = json.loads(builder_state) if builder_state else state.get("builder_state", {})
//
//      So a successful timeline_data write that includes builder_state / resolved_prompt
//      still queues the PREVIOUS prompt. That is #1935.
//
//   4. The pack's restore (`node.__dasiwaH3RestorePersistedState`) is rAF-wrapped and
//      prefers `builderWidget.value || state.builder_state`. Invoking it after a
//      timeline_data-only write rehydrates the STALE builder_state widget, not the new
//      nested JSON. It cannot verify prompt + builder_state synchronization in the same
//      turn, so it is not a drive path.
//
// WHY A REFUSAL AND NOT A ROUTE. LTXDirector (#314) ships `_applyLoadedTimeline`; this
// node does not. Guessing at the closure, writing three widgets, and hoping a rAF restore
// agrees would report success for a UI that still holds the old prompt. Refusing costs
// the caller one tool call. The verified workaround is the node's own
// `external_prompt_overwrite` input (forceInput STRING).
//
// duration / width / height / mode / frame_rate stay on the normal write path: they are
// not regenerated from builderState.
//
// Dependency-free. Unit-testable with plain fixtures.
// [MMX-MCP] Local patch: an explicit, verified node driver can own these writes.
// Unpatched nodes retain the original refusal; builder_state is never driven.

/** The DaSiWa node whose prompt is regenerated by its Director editor. */
export const MINIMAX_H3_DIRECTOR_TYPE = "MiniMaxH3Director";

/** The prompt widget this guard first covered (#1679). */
export const MINIMAX_H3_DIRECTOR_PROMPT_WIDGET = "prompt";
export const MINIMAX_H3_DIRECTOR_GLOBAL_PROMPT_WIDGET = "global_prompt";

/** Hidden JSON the editor parses into its in-memory timeline (#1935). */
export const MINIMAX_H3_DIRECTOR_TIMELINE_WIDGET = "timeline_data";

/** Hidden JSON emit() writes back from builderState (#1935). */
export const MINIMAX_H3_DIRECTOR_BUILDER_STATE_WIDGET = "builder_state";

/** The local Director recomputes this output from its segment durations. */
export const MINIMAX_H3_DIRECTOR_TOTAL_FRAMES_WIDGET = "total_frames";

/** Exact widget names emit() regenerates. Suffix-shaped addresses are not these widgets. */
export const MINIMAX_H3_DIRECTOR_DERIVED_WIDGETS = Object.freeze([
  MINIMAX_H3_DIRECTOR_PROMPT_WIDGET,
  MINIMAX_H3_DIRECTOR_BUILDER_STATE_WIDGET,
  MINIMAX_H3_DIRECTOR_TIMELINE_WIDGET,
  MINIMAX_H3_DIRECTOR_GLOBAL_PROMPT_WIDGET,
  MINIMAX_H3_DIRECTOR_TOTAL_FRAMES_WIDGET,
]);

/**
 * True for a MiniMaxH3Director node. Matches when EITHER `type` OR `comfyClass` is the
 * class name — not `type ?? comfyClass`, which would ignore a matching `comfyClass`
 * whenever `type` is a different non-null value (the #314 review finding).
 */
export function isMiniMaxH3DirectorNode(node) {
  if (!node || typeof node !== "object") return false;
  return node.type === MINIMAX_H3_DIRECTOR_TYPE || node.comfyClass === MINIMAX_H3_DIRECTOR_TYPE;
}

/**
 * "derived" only for the exact Director node type and the exact derived widget names.
 * Every other node and every other MiniMax widget stays on the normal write path.
 *
 * @param {{type?: unknown, comfyClass?: unknown}} node
 * @param {unknown} widgetName
 * @returns {"derived"|null}
 */
export function classifyMiniMaxH3DirectorWrite(node, widgetName) {
  if (!isMiniMaxH3DirectorNode(node)) return null;
  if (!MINIMAX_H3_DIRECTOR_DERIVED_WIDGETS.includes(widgetName)) return null;
  return externalSetterName(node, widgetName) ? null : "derived";
}

/** [MMX-MCP] Bounded, content-free evidence from the node that actually refused a write. */
export function miniMaxH3DirectorDriverDiagnostic(node, { origin, receiverIsLiveInstance, registeredConstructorMatches } = {}) {
  const read = getter => {
    try { return getter(); } catch { return "unreadable"; }
  };
  return {
    patch: "MMX-MCP-driver-diagnostic-20261007",
    node_id: read(() => node.id),
    type: read(() => node.type),
    timeline: read(() => typeof node.setExternalTimelineData),
    state: read(() => typeof node.getExternalPromptState),
    global: read(() => typeof node.setExternalGlobalPrompt),
    editor: read(() => !!node._minimaxEditor),
    editorTimeline: read(() => typeof node._minimaxEditor?.setExternalTimelineData),
    editorState: read(() => typeof node._minimaxEditor?.getExternalPromptState),
    uiPatched: read(() => node._minimaxDirectorPatched === true),
    constructor: read(() => node.constructor?.name),
    receiverIsLiveInstance,
    registeredConstructorMatches,
    origin,
  };
}

/** Capture once per full detail read; no implicit "latest read" baseline on writes. */
export function captureMiniMaxH3DirectorRead(node) {
  if (!isMiniMaxH3DirectorNode(node) || typeof node.getExternalWriteSnapshot !== "function") return null;
  const snapshot = node.getExternalWriteSnapshot();
  if (snapshot?.protocol !== "mmx-three-way-v1") return null;
  return snapshot;
}

function externalSetterName(node, widgetName) {
  if (widgetName === MINIMAX_H3_DIRECTOR_BUILDER_STATE_WIDGET
    || widgetName === MINIMAX_H3_DIRECTOR_TOTAL_FRAMES_WIDGET) return null;
  try {
    if (typeof node.setExternalTimelineData !== "function"
      || typeof node.getExternalPromptState !== "function"
      || typeof node.getExternalWriteSnapshot !== "function") return null;
    if (widgetName === MINIMAX_H3_DIRECTOR_TIMELINE_WIDGET) return "setExternalTimelineData";
    return typeof node.setExternalGlobalPrompt === "function" ? "setExternalGlobalPrompt" : null;
  } catch {
    return null;
  }
}

/** [MMX-MCP] Drive the editor in the normal undo envelope; never assign a raw widget. */
export function applyMiniMaxH3DirectorWrite(
  node,
  widgetName,
  value,
  { beforeChange, afterChange, setDirty, assertTargetStillCurrent } = {},
) {
  if (!isMiniMaxH3DirectorNode(node)
    || !MINIMAX_H3_DIRECTOR_DERIVED_WIDGETS.includes(widgetName)) return null;
  const via = externalSetterName(node, widgetName);
  if (!via) throw new Error(miniMaxH3DirectorPromptRefusal(widgetName, node.id));

  const findWidget = name => node.widgets?.find(widget => widget?.name === name);
  const timelineWidget = findWidget(MINIMAX_H3_DIRECTOR_TIMELINE_WIDGET);
  const promptWidget = findWidget(MINIMAX_H3_DIRECTOR_GLOBAL_PROMPT_WIDGET)
    ?? findWidget(MINIMAX_H3_DIRECTOR_PROMPT_WIDGET);
  if (!timelineWidget || !promptWidget) {
    throw new Error(`panel_set_widget cannot verify the Director widgets on node ${node.id}`);
  }
  const timelineWrite = widgetName === MINIMAX_H3_DIRECTOR_TIMELINE_WIDGET;
  // Parse before the undo boundary, but verify against the merged driver result.
  if (timelineWrite) JSON.parse(typeof value === "string" ? value : JSON.stringify(value));
  const previous = timelineWrite ? timelineWidget.value : promptWidget.value;
  let actual;
  let state;
  let result;
  beforeChange?.();
  try {
    assertTargetStillCurrent?.();
    if (externalSetterName(node, widgetName) !== via) {
      throw new Error(miniMaxH3DirectorPromptRefusal(widgetName, node.id));
    }
    // A timeline write already owns global.prompt; do not call the prompt setter again.
    result = node[via](value);
    if (result?.ok !== true) {
      throw new Error(`panel_set_widget ${via} failed on node ${node.id}: ${result?.error ?? "driver did not confirm success"}`);
    }
    state = node.getExternalPromptState();
    const saved = JSON.parse(timelineWidget.value);
    const confirmed = JSON.parse(result.timeline_data);
    const expectedPrompt = String(confirmed.global?.prompt ?? "");
    if (state?.protocol !== "mmx-three-way-v1" || state?.latched !== true || state?.sameAsTimeline !== true
      || promptWidget.value !== expectedPrompt || saved.global?.prompt !== expectedPrompt
      || timelineWidget.value !== result.timeline_data || !Array.isArray(result.conflicts)) {
      throw new Error(`panel_set_widget Director readback verification failed on node ${node.id}; re-read the node before retrying`);
    }
    actual = timelineWrite ? timelineWidget.value : promptWidget.value;
  } finally {
    afterChange?.();
  }
  setDirty?.();
  return {
    applied: true,
    chars: actual.length,
    via,
    latched: true,
    conflicts: result.conflicts,
    changed_paths: result.changed_paths,
    preserved_frontend_paths: result.preserved_frontend_paths,
    // Every successful Director write consumes the token across BOTH widgets.
    // Forward its fresh post-write baseline instead of leaving the Agent to
    // reuse the token from the earlier detail read.
    ...(result.minimax_h3_director_write
      ? { minimax_h3_director_write: result.minimax_h3_director_write }
      : { next_write_requires_detail_read: true }),
    set: { node_id: node.id, widget: widgetName, value: actual, previous },
    minimax_h3_director: { node_id: node.id, latched: true, sameAsTimeline: true, stamp: state.stamp, conflicts: result.conflicts, protocol: state.protocol },
  };
}

/**
 * Explain the silent-stale / silent-revert mechanism and the verified external override.
 */
export function miniMaxH3DirectorPromptRefusal(widgetName, nodeId) {
  if (widgetName === MINIMAX_H3_DIRECTOR_TOTAL_FRAMES_WIDGET) {
    return (
      `panel_set_widget cannot drive "${widgetName}" on ${MINIMAX_H3_DIRECTOR_TYPE} node ${nodeId}: ` +
      `total_frames is derived from the Director's in-memory segment durations and is ` +
      `recomputed by getTotalFrames() during commit(). A raw widget write cannot set ` +
      `the timeline length. Change segment durations in the Director timeline instead. ` +
      `The write was refused before any graph mutation; the existing segments and references ` +
      `were left unchanged.`
    );
  }
  return (
    `panel_set_widget cannot drive "${widgetName}" on ${MINIMAX_H3_DIRECTOR_TYPE} node ${nodeId}: ` +
    `timeline_data, builder_state, and prompt are DERIVED write-backs of the node's in-memory ` +
    `builderState. The Director editor parses timeline_data once at install, then emit() ` +
    `regenerates all three from that closure, so a raw write shows in panel_query_graph while ` +
    `prompt and builder_state stay stale and the next UI touch reverts it (#1935, #1679). ` +
    `Python execute() prefers the builder_state widget over timeline_data.builder_state when ` +
    `the widget is non-empty, so a successful timeline_data result does not mean the prompt ` +
    `changed. Use the node's supported external_prompt_overwrite path instead: connect a ` +
    `PrimitiveNode STRING output to "external_prompt_overwrite", then set the PrimitiveNode's ` +
    `STRING value with panel_set_widget. The write was refused before any graph mutation; ` +
    `other widgets and node types are unaffected.`
  );
}
